import {prepareCanvas, setMode} from "../roi.js";

const esc = (value) => String(value).replace(/[&<>"']/g, (char) => ({"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"}[char]));
let cleanupCanvas;

const friendly = (message) => ({
  signature_invalid: "Report signature is invalid. The report may have been changed.",
  wrong_session: "This report belongs to a different game session.",
  already_applied: "This clip has already been applied for this round.",
  unsupported_video_type: "Choose an MP4, WebM, or QuickTime video.",
  video_too_large: "The video is larger than the 300 MB upload limit.",
}[message] || message);

export async function renderJudge(root, {state, api, show, notify, refreshSession}) {
  if (!state.clip || !state.sessionId) return show("play");
  const game = state.game;
  const options = game.id === "football"
    ? [["goal_A", "Draw Goal A (defended by Team A)"], ["goal_B", "Draw Goal B (defended by Team B)"], ...state.session.players.map((p) => [`seed:${p.id}`, `Tap ${p.name || p.id}`])]
    : game.id === "bucket_toss"
      ? [["bowl", "Draw bucket opening"], ["seed:object", "Tap bean bag colour"]]
      : game.id === "majlis_freeze"
        ? state.session.players.map((p) => [`seed:${p.id}`, `Tap ${p.name || p.id}`])
        : [];
  const cueFields = game.id === "football" ? [] : game.id === "majlis_freeze" ? [["music_stop_s", "Music stop (seconds)"]]
    : game.id === "say_it_right" ? [["prompt_shown_s", "Prompt shown (seconds)"]]
      : game.id === "hand_duel" ? [["go_s", "GO cue (seconds)"]] : [];
  root.innerHTML = `
    <div class="eyebrow">Step 5 · AI judge results</div><h1>Review the referee's call</h1>
    <p class="lead">Mark the play area if needed, then run the game-specific AI judge. Every event includes a human-readable reason.</p>
    <div class="columns">
      <div class="panel">
        <h3>Clip: ${esc(state.clipName || "browser recording")}</h3>
        <div class="canvas-wrap"><canvas id="roiCanvas"></canvas></div>
        ${options.length ? `<p class="small muted">Select a marking tool, then draw a rectangle or tap a point on the first frame.</p><div class="cue-row">${options.map(([key, title]) => `<button class="btn outline roi-mode" data-mode="${esc(key)}">${esc(title)}</button>`).join("")}</div>` : `<p class="small muted">No marking is required for this game.</p>`}
        <div class="rules-list">${cueFields.map(([key, label]) => `<label class="field"><span>${esc(label)}</span><input type="number" step="0.1" min="0" data-cue-field="${key}" value="${state.cues[key] ?? ""}" placeholder="Add cue time"></label>`).join("")}
        ${game.id === "bucket_toss" ? state.session.players.map((p) => {
          const turn = state.cues.turns?.find((item) => item.player === p.id);
          return `<label class="field"><span>${esc(p.name)} turn start (s)</span><input type="number" step="0.1" min="0" data-turn-start="${p.id}" value="${turn?.start_s ?? ""}" placeholder="e.g. 0"></label>
          <label class="field"><span>${esc(p.name)} turn end (s)</span><input type="number" step="0.1" min="0" data-turn-end="${p.id}" value="${turn?.end_s ?? ""}" placeholder="e.g. 20"></label>`;
        }).join("") : ""}
        ${game.id === "bucket_toss" ? state.session.players.map((p) => `<label class="field"><span>${esc(p.name)} logged throws</span><input type="number" min="0" max="50" data-throws="${p.id}" value="${state.throwCount?.[p.id] || 0}"></label>`).join("") : ""}
        ${game.id === "say_it_right" ? `<label class="field"><span>Heritage question</span><select id="questionSelect">${state.questions.map((q) => `<option value="${q.id}" ${q.id === state.questionId ? "selected" : ""}>${esc(q.q_en)}</option>`).join("")}</select></label>` : ""}
        </div>
        <div class="button-row"><button class="btn primary" id="runJudge">⚖ Run AI judge</button></div>
        <div id="judgeStatus" style="margin-top:14px"></div>
        <div id="resultBlock"></div>
      </div>
      <aside class="panel">
        <h3>Standalone report</h3><p class="small muted">Paste a signed JSON report generated by <code>standalone_judge.py</code>. Editing even one report value invalidates its signature.</p>
        <label class="field"><span>Paste report JSON</span><textarea id="pasteReport" rows="9" spellcheck="false" placeholder='{"report": {...}, "signature": "..."}'></textarea></label>
        <button class="btn light" id="applyPasted">Verify & apply pasted report</button>
        <hr style="border:0;border-top:1px solid #e6eaf0;margin:20px 0">
        <h3>How it works</h3><p class="small muted">The local judge signs the complete report with HMAC-SHA256. The secret never leaves this server. Score changes are accepted only after signature verification.</p>
        <div class="button-row"><button class="btn light" id="backPlay">← Back to play</button></div>
      </aside>
    </div>`;
  const canvas = root.querySelector("#roiCanvas");
  try {
    cleanupCanvas?.();
    cleanupCanvas = await prepareCanvas(canvas, state.clip, {...state.rois, ...state.seeds}, (shapes) => {
      state.rois = Object.fromEntries(Object.entries(shapes).filter(([, value]) => value.length === 4));
      state.seeds = Object.fromEntries(Object.entries(shapes).filter(([, value]) => value.length === 2));
    });
  } catch (error) {
    notify(`Couldn't preview the first frame: ${error.message}. The clip can still be judged if this game doesn't need marks.`);
  }
  root.querySelectorAll(".roi-mode").forEach((button) => button.addEventListener("click", () => {
    setMode(button.dataset.mode);
    notify(`${button.textContent}: mark the video frame now.`, "success");
  }));
  root.querySelectorAll("[data-cue-field]").forEach((input) => input.addEventListener("change", () => {
    const value = input.value === "" ? undefined : Number(input.value);
    state.cues[input.dataset.cueField] = value;
  }));
  const updateTurns = () => {
    state.cues.turns = state.session.players.map((player) => ({
      player: player.id,
      start_s: Number(root.querySelector(`[data-turn-start="${player.id}"]`)?.value || 0),
      end_s: Number(root.querySelector(`[data-turn-end="${player.id}"]`)?.value || 0),
    })).filter((turn) => turn.end_s > turn.start_s);
  };
  root.querySelectorAll("[data-turn-start], [data-turn-end]").forEach((input) => input.addEventListener("change", updateTurns));
  root.querySelector("#questionSelect")?.addEventListener("change", (event) => { state.questionId = event.target.value; });
  root.querySelectorAll("[data-throws]").forEach((input) => input.addEventListener("change", () => {
    state.throwCount ||= {};
    state.throwCount[input.dataset.throws] = Number(input.value);
  }));
  root.querySelector("#runJudge").addEventListener("click", async () => {
    const button = root.querySelector("#runJudge");
    button.disabled = true;
    button.innerHTML = '<span class="spinner"></span> Judging clip…';
    const started = Date.now();
    const elapsed = setInterval(() => {
      button.innerHTML = `<span class="spinner"></span> Judging ${Math.floor((Date.now() - started) / 1000)}s…`;
    }, 1000);
    try {
      const cues = {...state.cues};
      root.querySelectorAll("[data-cue-field]").forEach((input) => {
        if (input.value !== "") cues[input.dataset.cueField] = Number(input.value);
      });
      if (game.id === "bucket_toss") {
        cues.turns = state.session.players.map((player) => ({
          player: player.id,
          start_s: Number(root.querySelector(`[data-turn-start="${player.id}"]`).value || 0),
          end_s: Number(root.querySelector(`[data-turn-end="${player.id}"]`).value || 0),
        })).filter((turn) => turn.end_s > turn.start_s);
      }
      const config = {
        session_id: state.sessionId, game: game.id, round: state.session.round,
        rois: state.rois, seeds: state.seeds, players: state.session.players.map((p) => p.id),
        teams: state.session.teams, cues, rules: state.session.rules,
        question_id: state.questionId, throw_count: state.throwCount || {},
      };
      state.reportBundle = await api.judgeVideo(state.sessionId, state.clip, config);
      renderReport(root, state, state.reportBundle, null, refreshSession);
    } catch (error) {
      notify(friendly(error.message));
    } finally {
      clearInterval(elapsed);
      button.disabled = false;
      button.textContent = "⚖ Run AI judge";
    }
  });
  root.querySelector("#applyPasted").addEventListener("click", async () => {
    try {
      const bundle = JSON.parse(root.querySelector("#pasteReport").value);
      if (!bundle.report || !bundle.signature) throw new Error("Paste a JSON object with report and signature fields.");
      state.reportBundle = bundle;
      await apply(bundle);
    } catch (error) {
      renderStatus(root, false, friendly(error.message));
    }
  });
  root.querySelector("#backPlay").addEventListener("click", () => show("play"));
  if (state.reportBundle) renderReport(root, state, state.reportBundle, state.applyError || null, refreshSession);
  if (state.applied) {
    root.querySelector("#resultBlock").insertAdjacentHTML("beforeend", `<div class="button-row"><button class="btn primary" id="nextRound">${state.session.status === "finished" ? "View final results →" : "Next round / turn →"}</button></div>`);
    root.querySelector("#nextRound").addEventListener("click", async () => {
      const result = await api.nextTurn(state.sessionId);
      await refreshSession();
      if (result.state.status === "finished") await show("results");
      else {
        state.applied = false;
        state.reportBundle = null;
        state.clip = null;
        state.clipName = null;
        state.rois = {};
        state.seeds = {};
        state.cues = {};
        await show("play");
      }
    });
  }

  async function apply(bundle) {
    try {
      const response = await api.applyReport(state.sessionId, {report: bundle.report, signature: bundle.signature});
      state.session = response.state;
      await refreshSession();
      state.applied = true;
      state.applyError = null;
      renderStatus(root, true, "Signature verified — AI results applied to the live score.");
      renderReport(root, state, bundle, null, refreshSession);
      if (!root.querySelector("#nextRound")) {
        root.querySelector("#resultBlock").insertAdjacentHTML("beforeend", `<div class="button-row"><button class="btn primary" id="nextRound">${state.session.round >= state.session.total_rounds ? "View final results →" : "Next round / turn →"}</button></div>`);
        root.querySelector("#nextRound").addEventListener("click", async () => {
          const next = await api.nextTurn(state.sessionId);
          await refreshSession();
          if (next.state.status === "finished") await show("results");
          else {
            state.applied = false; state.reportBundle = null; state.clip = null; state.clipName = null; state.rois = {}; state.seeds = {}; state.cues = {};
            await show("play");
          }
        });
      }
    } catch (error) {
      state.applyError = friendly(error.message);
      renderStatus(root, false, state.applyError);
    }
  }
}

function renderStatus(root, verified, message) {
  const target = root.querySelector("#judgeStatus");
  if (target) target.innerHTML = `<div class="status ${verified ? "verified" : "tampered"}">${verified ? "✓ VERIFIED" : "✕ NOT VERIFIED"} · ${esc(message)}</div>`;
}

function renderReport(root, state, bundle, error, refreshSession) {
  const {report, signature, annotated_video_url: annotated} = bundle;
  renderStatus(root, Boolean(state.applied), state.applied ? "Signature verified — score updated." : "Signed by the local AI judge. Apply to verify and update the score.");
  if (error) renderStatus(root, false, error);
  const videoMarkup = annotated ? `<video id="annotatedVideo" controls playsinline src="${esc(annotated)}"></video>` : "";
  const events = (report.events || []).map((event) => `<div class="event"><button data-seek="${Number(event.t) || 0}">${Number(event.t || 0).toFixed(1)}s · ${esc(event.type)}</button><p>${esc(event.reason || "")}</p></div>`).join("") || `<p class="muted">No events were detected in this clip.</p>`;
  root.querySelector("#resultBlock").innerHTML = `
    <div style="margin-top:22px"><h2>Judge's report</h2><p>${esc(report.summary || "")}</p>
    ${videoMarkup}
    <h3 style="margin-top:18px">Events & reasons</h3><div class="event-list">${events}</div>
    <details style="margin-top:14px"><summary>Detection stats</summary><pre style="overflow:auto;white-space:pre-wrap">${esc(JSON.stringify(report.stats || {}, null, 2))}</pre></details>
    <details style="margin-top:10px"><summary>Signed report JSON</summary><pre style="overflow:auto;white-space:pre-wrap">${esc(JSON.stringify({report, signature}, null, 2))}</pre></details>
    <div class="button-row"><button class="btn good" id="applyResults" ${state.applied ? "disabled" : ""}>${state.applied ? "✓ Results applied" : "Apply AI results"}</button></div></div>`;
  root.querySelectorAll("[data-seek]").forEach((button) => button.addEventListener("click", () => {
    const player = root.querySelector("#annotatedVideo");
    if (player) { player.currentTime = Number(button.dataset.seek); player.play(); }
  }));
  root.querySelector("#applyResults")?.addEventListener("click", () => applyAndRerender());
  async function applyAndRerender() {
    try {
      const response = await (await import("../api.js")).applyReport(state.sessionId, {report, signature});
      state.session = response.state;
      await refreshSession();
      state.applied = true;
      renderStatus(root, true, "Signature verified — AI results applied to the live score.");
      renderReport(root, state, bundle, null, refreshSession);
      if (!root.querySelector("#nextRound")) {
        root.querySelector("#resultBlock").insertAdjacentHTML("beforeend", `<div class="button-row"><button class="btn primary" id="nextRound">${state.session.round >= state.session.total_rounds ? "View final results →" : "Next round / turn →"}</button></div>`);
        root.querySelector("#nextRound").addEventListener("click", async () => {
          const {nextTurn} = await import("../api.js");
          const next = await nextTurn(state.sessionId);
          await refreshSession();
          if (next.state.status === "finished") await (await import("../app.js")).show("results");
          else {
            state.applied = false; state.reportBundle = null; state.clip = null; state.clipName = null; state.rois = {}; state.seeds = {}; state.cues = {};
            await (await import("../app.js")).show("play");
          }
        });
      }
    } catch (applyError) {
      renderStatus(root, false, friendly(applyError.message));
    }
  }
}
